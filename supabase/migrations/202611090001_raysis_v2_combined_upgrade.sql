-- Raysis V2 coordinated upgrade: idempotent offline-write keys, audit log, correction requests.
-- Run once in Supabase SQL Editor after reviewing. Do not run from the browser.
begin;

alter table public.sales add column if not exists client_operation_id uuid;
alter table public.quotations add column if not exists client_operation_id uuid;
alter table public.stock_movements add column if not exists client_operation_id uuid;
alter table public.payments add column if not exists client_operation_id uuid;

create unique index if not exists sales_client_operation_id_uidx on public.sales(client_operation_id) where client_operation_id is not null;
create unique index if not exists quotations_client_operation_id_uidx on public.quotations(client_operation_id) where client_operation_id is not null;
create unique index if not exists stock_movements_client_operation_id_uidx on public.stock_movements(client_operation_id) where client_operation_id is not null;
create unique index if not exists payments_client_operation_id_uidx on public.payments(client_operation_id) where client_operation_id is not null;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_id uuid,
  branch_name text,
  table_name text not null,
  record_id text,
  action text not null,
  old_data jsonb,
  new_data jsonb
);
alter table public.audit_logs enable row level security;
drop policy if exists "Audit logs visible to own branch and CEO" on public.audit_logs;
create policy "Audit logs visible to own branch and CEO"
on public.audit_logs for select to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid()
    and (p.role = 'ceo' or p.branch_name = audit_logs.branch_name)
));
revoke all on public.audit_logs from anon, authenticated;
grant select on public.audit_logs to authenticated;

create or replace function public.capture_raysis_audit()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_branch text;
  v_id text;
begin
  if TG_OP = 'DELETE' then
    v_old := to_jsonb(OLD);
    v_branch := v_old ->> 'branch_name';
    v_id := coalesce(v_old ->> 'id', v_old ->> 'receipt_number', v_old ->> 'quotation_number');
  elsif TG_OP = 'UPDATE' then
    v_old := to_jsonb(OLD);
    v_new := to_jsonb(NEW);
    v_branch := coalesce(v_new ->> 'branch_name', v_old ->> 'branch_name');
    v_id := coalesce(v_new ->> 'id', v_new ->> 'receipt_number', v_new ->> 'quotation_number');
  else
    v_new := to_jsonb(NEW);
    v_branch := v_new ->> 'branch_name';
    v_id := coalesce(v_new ->> 'id', v_new ->> 'receipt_number', v_new ->> 'quotation_number');
  end if;
  insert into public.audit_logs(actor_id, branch_name, table_name, record_id, action, old_data, new_data)
  values (auth.uid(), v_branch, TG_TABLE_NAME, v_id, TG_OP, v_old, v_new);
  if TG_OP = 'DELETE' then return OLD; else return NEW; end if;
end;
$$;

drop trigger if exists raysis_audit_sales on public.sales;
create trigger raysis_audit_sales after insert or update or delete on public.sales
for each row execute function public.capture_raysis_audit();
drop trigger if exists raysis_audit_quotations on public.quotations;
create trigger raysis_audit_quotations after insert or update or delete on public.quotations
for each row execute function public.capture_raysis_audit();
drop trigger if exists raysis_audit_stock_movements on public.stock_movements;
create trigger raysis_audit_stock_movements after insert or update or delete on public.stock_movements
for each row execute function public.capture_raysis_audit();
drop trigger if exists raysis_audit_payments on public.payments;
create trigger raysis_audit_payments after insert or update or delete on public.payments
for each row execute function public.capture_raysis_audit();

create table if not exists public.correction_requests (
  id bigint generated by default as identity primary key,
  branch_name text not null,
  entity_type text not null check (entity_type in ('sale','quotation','stock_movement','payment')),
  entity_id text not null,
  reason text not null,
  proposed_changes jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  requested_by uuid not null default auth.uid(),
  requested_at timestamptz not null default now(),
  reviewed_by uuid,
  reviewed_at timestamptz,
  review_note text
);
alter table public.correction_requests enable row level security;
drop policy if exists "Users read own branch correction requests" on public.correction_requests;
create policy "Users read own branch correction requests"
on public.correction_requests for select to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid()
    and (p.role = 'ceo' or p.branch_name = correction_requests.branch_name)
));
drop policy if exists "Branch users submit correction requests" on public.correction_requests;
create policy "Branch users submit correction requests"
on public.correction_requests for insert to authenticated
with check (
  requested_by = auth.uid() and status = 'pending' and reviewed_by is null
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'branch_user'
      and p.branch_name = correction_requests.branch_name
  )
);
drop policy if exists "CEO reviews correction requests" on public.correction_requests;
create policy "CEO reviews correction requests"
on public.correction_requests for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'ceo'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'ceo'));

revoke all on public.correction_requests from anon;
grant select, insert, update on public.correction_requests to authenticated;
revoke delete on public.correction_requests from authenticated;
grant usage, select on sequence public.correction_requests_id_seq to authenticated;

-- Include request submission and CEO review in the same immutable audit history.
drop trigger if exists raysis_audit_correction_requests on public.correction_requests;
create trigger raysis_audit_correction_requests
after insert or update or delete on public.correction_requests
for each row execute function public.capture_raysis_audit();

commit;
